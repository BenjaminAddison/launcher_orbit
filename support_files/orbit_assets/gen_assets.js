// Generates src/orbit/orbit_assets.h + orbit_assets.cpp from the Orbit UI's font, sprite
// and theme tables in art/ (the same files the design mockup runs on), so the device
// draws exactly what the mockup shows. The header only declares; the data lives once,
// in the .cpp. usage: node support_files/orbit_assets/gen_assets.js [outdir]
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, 'art');
const ctx = { console, Math, Array, Object, String, Number, JSON, Uint8Array, Uint32Array, Set };
vm.createContext(ctx);
for (const f of ['00_core.js', '10_fonts.js', '20_theme.js', '30_sprites.js']) vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), ctx, { filename: f });
const get = (n) => vm.runInContext(n, ctx);
const FONT_SRC = get('FONT_SRC'), THEMES = get('THEMES'), TOKENS = get('TOKENS');
const out = [], hdr = [];
const hex2 = (b) => '0x' + b.toString(16).padStart(2, '0');
const arr = (type, name, vals, perLine = 24) => {
  if (!vals.length) { out.push(`static const ${type} *const ${name} = nullptr;`); return; }
  out.push(`static const ${type} ${name}[${vals.length}] = {`);
  for (let i = 0; i < vals.length; i += perLine) out.push('  ' + vals.slice(i, i + perLine).join(', ') + ',');
  out.push('};');
};
const banner = '// Generated by support_files/orbit_assets/gen_assets.js from the Orbit art tables. Do not edit by hand.';
hdr.push(banner, '#pragma once', '#include <stdint.h>', 'namespace orb {');
out.push(banner, '#if defined(ORBIT_UI) || defined(ORBIT_NATIVE)', '#include "orbit_assets.h"', 'namespace orb {');

// ── fonts ──
const FONT_ORDER = ['MICRO', 'BODY', 'ORBIT'];
hdr.push('enum FontId : uint8_t { F_MICRO, F_BODY, F_ORBIT };');
hdr.push('struct FontDef { uint8_t h, sp, space, nspecial; const uint8_t *ascii; const uint16_t *specialCp; const uint8_t *specialIdx; const uint8_t *widths; const uint16_t *offs; const uint8_t *bits; };');
for (const name of FONT_ORDER) {
  const src = FONT_SRC[name], glyphs = Object.entries(src.glyphs);
  const widths = [], offs = [], bits = []; let bitpos = 0;
  const index = {};
  glyphs.forEach(([ch, rowsStr], gi) => {
    const rows = rowsStr.split('|'), w = Math.max(...rows.map(r => r.length));
    index[ch] = gi; widths.push(w); offs.push(bitpos);
    for (let j = 0; j < src.h; j++) for (let i = 0; i < w; i++) { const on = rows[j] && rows[j][i] === '#'; if (on) bits[bitpos >> 3] = (bits[bitpos >> 3] || 0) | (1 << (bitpos & 7)); bitpos++; }
  });
  const nbytes = (bitpos + 7) >> 3; for (let i = 0; i < nbytes; i++) bits[i] = bits[i] || 0;
  const q = index['?'];
  const ascii = [];
  for (let c = 32; c < 128; c++) {
    const ch = String.fromCharCode(c);
    let gi = index[ch]; if (gi === undefined) gi = index[ch.toUpperCase()]; if (gi === undefined) gi = index[ch.toLowerCase()];
    ascii.push(c === 32 ? 255 : (gi === undefined ? q : gi));
  }
  const specials = glyphs.map(([ch], gi) => [ch.codePointAt(0), gi]).filter(([cp]) => cp > 127).sort((a, b) => a[0] - b[0]);
  const N = name.toLowerCase();
  arr('uint8_t', `${N}_ascii`, ascii);
  arr('uint16_t', `${N}_spcp`, specials.map(s => '0x' + s[0].toString(16)));
  arr('uint8_t', `${N}_spidx`, specials.map(s => s[1]));
  arr('uint8_t', `${N}_w`, widths);
  arr('uint16_t', `${N}_offs`, offs);
  arr('uint8_t', `${N}_bits`, bits.map(hex2));
  out.push(`static const FontDef FONT_${name} = { ${src.h}, ${src.sp}, ${src.space}, ${specials.length}, ${N}_ascii, ${N}_spcp, ${N}_spidx, ${N}_w, ${N}_offs, ${N}_bits };`);
}
out.push('extern const FontDef *const FONTS[3] = { &FONT_MICRO, &FONT_BODY, &FONT_ORBIT };');
hdr.push('extern const FontDef *const FONTS[3];');

// ── sprites (indexed, palette = chars resolved at draw time), run-length coded:
// each byte is (run length - 1) << 4 | colour index (0 = clear), row-major ──
hdr.push('struct SpriteDef { uint8_t w, h, npal; const char *pal; const uint8_t *px; }; // px: runs, (len-1)<<4 | index');
const sprites = [];
const ICON = get('ICON');
const spriteList = [['ICO_SD', ICON.sd], ['ICO_OTA', ICON.ota], ['ICO_WUI', ICON.wui], ['ICO_USB', ICON.usb], ['ICO_PMAN', ICON.pman], ['ICO_CFG', ICON.cfg], ['ICO_CHG', ICON.chg], ['ICO_OFF', ICON.off], ['ICO_APP', ICON.app], ['SPR_ROCKET', get('ROCKET')], ['SPR_MINIROCKET', get('MINI_ROCKET')], ['SPR_SAT', get('SAT')]];
for (const [name, s] of spriteList) {
  const chars = [...new Set(s.d.split('').filter(c => c !== '.'))];
  if (chars.length > 15) throw new Error(name + ' uses too many colours: ' + chars.length);
  const idx = (c) => c === '.' ? 0 : chars.indexOf(c) + 1;
  const px = [];
  for (let i = 0, n = s.w * s.h; i < n;) {
    let r = 1;
    while (r < 16 && i + r < n && s.d[i + r] === s.d[i]) r++;
    px.push(hex2(((r - 1) << 4) | idx(s.d[i])));
    i += r;
  }
  arr('uint8_t', name.toLowerCase() + '_px', px);
  out.push(`extern const SpriteDef ${name} = { ${s.w}, ${s.h}, ${chars.length}, ${JSON.stringify(chars.join(''))}, ${name.toLowerCase()}_px };`);
  hdr.push(`extern const SpriteDef ${name};`);
  sprites.push(name);
}

// ── glyph icons (2bpp: 0 clear, 1 '#', 2 '+') ──
const GLYPH = get('GLYPH'), gnames = Object.keys(GLYPH);
hdr.push('enum GlyphId : uint8_t { ' + gnames.map(n => 'G_' + n.toUpperCase()).join(', ') + ', G_COUNT };');
const gw = [], gh = [], goff = [], gbits = []; let gb = 0;
for (const n of gnames) {
  const s = GLYPH[n]; gw.push(s.w); gh.push(s.h); goff.push(gb);
  for (let i = 0; i < s.w * s.h; i++) { const v = s.d[i] === '#' ? 1 : s.d[i] === '+' ? 2 : 0; gbits[gb >> 2] = (gbits[gb >> 2] || 0) | (v << ((gb & 3) * 2)); gb++; }
}
for (let i = 0; i < (gb + 3) >> 2; i++) gbits[i] = gbits[i] || 0;
for (const [type, name, vals] of [['uint8_t', 'glyph_w', gw], ['uint8_t', 'glyph_h', gh], ['uint16_t', 'glyph_off', goff], ['uint8_t', 'glyph_bits', gbits.map(hex2)]]) {
  const start = out.length; arr(type, name, vals); out[start] = out[start].replace('static const', 'extern const');
  hdr.push(`extern const ${type} ${name}[${vals.length}];`);
}

// ── themes ──
const applyTheme = get('applyTheme');
const RAWOF = () => get('RAW');
const allTok = [...TOKENS, 'accM', 'secM', 'lineM', 'textM', 'black', 'gold', 'goldD', 'goldL', 'flame0', 'flame1', 'flame2', 'flame3', 'ink', 'secL', 'errD', 'errL', 'okL', 'okD'];
hdr.push('enum Tok : uint8_t { ' + allTok.map(t => 'T_' + t).join(', ') + ', T_COUNT };');
const c565 = get('c565');
const themeRows = [];
for (const th of THEMES) { applyTheme(th.key); const raw = RAWOF(); themeRows.push('  { ' + allTok.map(t => '0x' + c565(raw[t]).v.toString(16).padStart(4, '0')).join(', ') + ' },'); }
out.push(`extern const uint16_t THEME_COLORS[${THEMES.length}][T_COUNT] = {`); out.push(...themeRows); out.push('};');
out.push(`extern const char *const THEME_NAMES[${THEMES.length}] = { ${THEMES.map(t => JSON.stringify(t.name)).join(', ')} };`);
out.push(`extern const char *const THEME_WAS[${THEMES.length}] = { ${THEMES.map(t => JSON.stringify(t.was)).join(', ')} };`);
out.push(`extern const char *const THEME_NOTE[${THEMES.length}] = { ${THEMES.map(t => JSON.stringify(t.note)).join(', ')} };`);
hdr.push(`constexpr uint8_t THEME_COUNT = ${THEMES.length};`);
hdr.push(`extern const uint16_t THEME_COLORS[THEME_COUNT][T_COUNT];`, `extern const char *const THEME_NAMES[THEME_COUNT];`, `extern const char *const THEME_WAS[THEME_COUNT];`, `extern const char *const THEME_NOTE[THEME_COUNT];`);
out.push('} // namespace orb', '#endif');
hdr.push('} // namespace orb');
const dir = process.argv[2] || path.join(__dirname, '..', '..', 'src', 'orbit');
fs.writeFileSync(path.join(dir, 'orbit_assets.h'), hdr.join('\n') + '\n');
fs.writeFileSync(path.join(dir, 'orbit_assets.cpp'), out.join('\n') + '\n');
console.log('wrote', dir, sprites.length, 'sprites,', gnames.length, 'glyphs');
